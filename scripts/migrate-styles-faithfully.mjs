import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";
import postcss from "postcss";

// Keep selectors, source order, media queries and animation rules intact. Only
// declarations with a lossless Tailwind arbitrary-property representation move.
const require = createRequire(import.meta.url);
const tailwindRequire = createRequire(require.resolve("@tailwindcss/postcss"));
const { compile } = tailwindRequire("@tailwindcss/node");
const root = resolve(import.meta.dirname, "..");
const inputPath = resolve(root, "src/styles/legacy.css");
const outputPath = resolve(root, "src/styles/fidelity.css");
const source = readFileSync(inputPath, "utf8");
const tree = postcss.parse(source);
let converted = 0;
tree.walkDecls((declaration) => {
  if (declaration.prop.startsWith("--") || declaration.important) return;
  // Strings, URLs and escapes retain their exact native CSS spelling.
  if (/["'\\_\[\];]/.test(declaration.value) || /url\(/i.test(declaration.value)) return;
  let ancestor = declaration.parent;
  while (ancestor) {
    if (ancestor.type === "atrule" && /keyframes|font-face|property/.test(ancestor.name)) return;
    ancestor = ancestor.parent;
  }
  if (declaration.parent.type !== "rule") return;
  const value = declaration.value.trim().replace(/\s+/g, "_");
  declaration.replaceWith(postcss.atRule({
    name: "apply",
    params: `[${declaration.prop}:${value}]`,
    raws: { before: declaration.raws.before },
  }));
  converted++;
});
const migrated = tree.toString();
const options = { base: root, onDependency() {} };
const before = (await compile(`@reference "tailwindcss";\n${source}`, options)).build([]);
const after = (await compile(`@reference "tailwindcss";\n${migrated}`, options)).build([]);
function structure(css) {
  function visit(node) {
    if (node.type === "comment") return null;
    const result = { type: node.type };
    for (const key of ["selector", "name", "params", "prop", "value", "important"]) {
      if (node[key] !== undefined) result[key] = typeof node[key] === "string"
        ? node[key].replace(/\s+/g, " ").replace(/\s*,\s*/g, ",").trim()
        : node[key];
    }
    if (node.nodes) result.nodes = node.nodes.map(visit).filter(Boolean);
    return result;
  }
  return visit(postcss.parse(css));
}
assert.deepEqual(structure(after), structure(before), "Tailwind changed the original CSS semantics");
const header = "/* Generated by scripts/migrate-styles-faithfully.mjs. Edit legacy.css, then regenerate. */\n";
if (process.argv.includes("--write")) writeFileSync(outputPath, header + migrated);
else assert.equal(readFileSync(outputPath, "utf8"), header + migrated, "Regenerate fidelity.css with --write");
console.log(`Verified ${converted} Tailwind declarations: identical selectors, values, cascade and animations.`);
