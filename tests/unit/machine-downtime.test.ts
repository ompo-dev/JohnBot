import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { transformMachineDowntime } from "../../src/lib/machine-downtime-analysis";
const csv = readFileSync("public/datasets/machine-downtime.csv", "utf8");
const result = transformMachineDowntime(csv);
assert.equal(result.bronze.csv, csv);
assert.equal(result.bronze.records, 2500);
assert.equal(result.gold.byMachine.length, 3);
assert.equal(result.gold.byLine.length, 3);
assert.equal(result.gold.records + result.silver.rejected.length + result.silver.duplicates + result.silver.blankRows, 2500);
assert(result.silver.rows.every((row) => /^\d{4}-\d{2}-\d{2}$/u.test(row.date)));
const [header, row] = csv.trim().split(/\r?\n/u);
const invalid = row.replace("31-12-2021", "31-02-2021");
const sample = transformMachineDowntime([header, row, row, invalid, row.replace(",71.04,", ",, ")].join("\n"));
assert.equal(sample.silver.duplicates, 1);
assert.equal(sample.silver.rejected.length, 1);
assert.equal(sample.silver.missingValues, 1);
assert.equal(sample.gold.records, 2);
console.log("PASS Bronze/Prata/Ouro:", JSON.stringify({ input: result.bronze.records, clean: result.gold.records, rejected: result.silver.rejected.length, duplicates: result.silver.duplicates, failures: result.gold.failures }));
