import assert from "node:assert/strict";
import { readWorkspaceValue, resetWorkspaceStore, updateWorkspaceValue, workspaceKey, workspaceStore } from "../../src/stores/workspace-store";
const one = workspaceKey("local", "conversations"), other = workspaceKey("remote", "conversations");
resetWorkspaceStore();
const initial = { messages: ["first"] };
assert.equal(readWorkspaceValue(one, initial), initial);
assert.equal(readWorkspaceValue(one, { messages: [] }), initial, "Remounts reuse the workspace's existing value");
let notifications = 0;
const unsubscribe = workspaceStore.subscribe(() => notifications++);
updateWorkspaceValue(one, initial, (current) => ({ messages: [...current.messages, "second"] }));
assert.deepEqual(initial.messages, ["first"]);
assert.deepEqual(readWorkspaceValue(one, initial).messages, ["first", "second"]);
assert.deepEqual(readWorkspaceValue(other, { messages: [] }).messages, []);
const count = notifications;
updateWorkspaceValue(one, initial, (current) => current);
assert.equal(notifications, count, "No-op updates do not cause render loops");
resetWorkspaceStore();
assert.deepEqual(readWorkspaceValue(one, { messages: [] }).messages, []);
unsubscribe();
console.log("PASS: workspace state survives remounts, isolates servers, preserves previous values and clears on session reset");
