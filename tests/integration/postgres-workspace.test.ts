import assert from "node:assert/strict";
import { loadEnvConfig } from "@next/env";
import { getDatabase, closeDatabase } from "../../src/server/database/client";
import { closeRedis } from "../../src/server/cache/redis";
import { resetServerEnvForTests } from "../../src/server/config/env";
import { readAgents, readConversation } from "../../src/server/services/agents";
import { createAgent, saveAgent, sendMessage, changeMessage, deleteAgent } from "../../src/server/services/workspace";
import { readSidebar, changeSidebar, readMemories, changeMemory, readWorkflowRuns } from "../../src/server/services/workspace-ui";
import { readStore } from "../../src/server/services/workflows";
import { createAgentSchema, sentMessageSchema } from "../../src/contracts/workspace-data";
loadEnvConfig(process.cwd());
process.env.JOHNBOT_DATA_MODE = "postgres";
resetServerEnvForTests();
const session = `workspace-${crypto.randomUUID()}`, other = `${session}-other`;
try {
  assert.deepEqual(await readAgents(session), []);
  assert.deepEqual(await readStore(session, "local"), [], "A fresh workspace has no example workflows");
  const id = crypto.randomUUID();
  const agent = await createAgent(session, createAgentSchema.parse({ id, name: "Persisted agent", description: "", avatarSeed: "agent", avatarHue: null }));
  assert.equal(agent.id, id);
  assert.equal((await readAgents(session)).length, 1);
  assert.deepEqual(await readAgents(other), []);
  const edited = await saveAgent(session, { ...agent, name: "Edited" }, agent.updatedAt);
  await assert.rejects(saveAgent(session, { ...agent, name: "Stale" }, agent.updatedAt), /another client/);
  assert.equal((await readAgents(session))[0]?.name, edited.name);
  const input = { agentId: id, clientMessageId: crypto.randomUUID(), text: "A real persisted message" };
  const sent = sentMessageSchema.parse(await sendMessage(session, input));
  await sendMessage(session, input);
  assert.equal((await readConversation(session, id)).snapshot.messages.length, 1, "Client IDs prevent duplicate messages");
  assert.equal(sent.receipt.deliveries[0]?.status, "queued");
  assert.equal(sent.conversation.snapshot.messages.some((item) => item.author === "agent"), false, "No invented assistant reply");
  await assert.rejects(sendMessage(session, { ...input, text: "different" }), /different content/);
  await assert.rejects(sendMessage(other, input), /Agent not found/);
  await changeMessage(session, { agentId: id, action: "reaction", messageId: input.clientMessageId, emoji: "👍" });
  assert.equal((await readConversation(session, id)).snapshot.messages[0]?.reaction, "👍");
  assert.deepEqual((await readConversation(session, id)).snapshot.messages[0]?.reactions, [{ emoji: "👍", actor: { kind: "user" } }]);
  await changeMessage(session, { agentId: id, action: "cancel" });
  assert.equal((await readConversation(session, id)).queue.deliveries[0]?.status, "cancelled");
  const sidebar = await readSidebar(session);
  await changeSidebar(session, { kind: "layout", expectedRevision: 0, layout: { ...sidebar.layout, sections: [{ id: "folder", name: "Saved" }], order: [...sidebar.layout.order, "folder"] } });
  await assert.rejects(changeSidebar(session, { kind: "layout", expectedRevision: 0, layout: sidebar.layout }), /another client/);
  assert.equal((await readSidebar(session)).layout.sections[0]?.name, "Saved");
  const memoryId = crypto.randomUUID();
  await changeMemory(session, { agentId: id, action: "create", memoryId, text: "Remember this" });
  assert.equal((await readMemories(session, id))[0]?.text, "Remember this");
  await closeDatabase(); await closeRedis();
  assert.equal((await readConversation(session, id)).snapshot.messages[0]?.text, input.text, "History survives reconnect");
  assert.deepEqual((await readWorkflowRuns(session, "local", "wf")).runs, []);
  await deleteAgent(session, id);
  await assert.rejects(readConversation(session, id), /Agent not found/);
  console.log("PASS: PostgreSQL-owned empty workspace, CRUD, conflicts, durable messages/queue/sidebar/memory, isolation and reconnect; no simulated replies");
} finally {
  await getDatabase().domainRecord.deleteMany({ where: { sessionId: { in: [session, other] } } });
  await closeRedis(); await closeDatabase();
}
